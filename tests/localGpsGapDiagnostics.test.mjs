import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createGpsSprint,advanceLiveGpsSprint,syntheticPoint,gpsGapDiagnostics} from '../src/lib/sprintGps.ts';
import {ghostTraceDiagnostics,ghostSummary} from '../src/lib/ghostRunSummary.ts';
import {createDuelGpsMeasurement,advanceDuelGpsMeasurement,resumeDuelGpsMeasurement} from '../src/lib/duelGpsMeasurement.ts';
const start=1700000000000;
const apply=(s,m,t,a=3)=>advanceLiveGpsSprint(s,syntheticPoint(m,start+t,a),start+t);
test('only accepted long gaps increment local diagnostics, including repeated gaps',()=>{
 let s=createGpsSprint(50,start);
 assert.deepEqual(gpsGapDiagnostics(s),{gpsObservationGapCount:0,gpsLongestObservationGapMs:null,finishTimingMethod:null});
 s=apply(s,0,0);
 s=apply(s,10,3000);
 assert.equal(gpsGapDiagnostics(s).gpsObservationGapCount,0);
 s=apply(s,20,6000,30);
 assert.equal(gpsGapDiagnostics(s).gpsObservationGapCount,0);
 s=apply(s,22,6500);
 assert.equal(gpsGapDiagnostics(s).gpsLongestObservationGapMs,3500);
 s=apply(s,54,10500);
 assert.equal(gpsGapDiagnostics(s).gpsObservationGapCount,2);
 assert.equal(gpsGapDiagnostics(s).gpsLongestObservationGapMs,4000);
 assert.equal(gpsGapDiagnostics(s).finishTimingMethod,null);
 s=apply(s,59,11500);
 assert.deepEqual(gpsGapDiagnostics(s),{gpsObservationGapCount:2,gpsLongestObservationGapMs:4000,finishTimingMethod:'observed-after-gap'});
 assert.deepEqual(gpsGapDiagnostics(apply(s,65,18000)),gpsGapDiagnostics(s));
});
test('normal crossings remain interpolated and short explicit recovery is not a long GPS interval',()=>{
 let s=createGpsSprint(50,start);
 for(let i=0;i<5;i++)s=apply(s,i*10,i*1000);
 s=apply(s,51,5000);s=apply(s,56,6000);
 assert.equal(gpsGapDiagnostics(s).finishTimingMethod,'interpolated');
 assert.equal(gpsGapDiagnostics(s).gpsObservationGapCount,0);
 let d=createDuelGpsMeasurement(50,start,null);
 for(let i=0;i<5;i++)d=advanceDuelGpsMeasurement(d,syntheticPoint(i*10,start+i*1000),start+i*1000);
 d=resumeDuelGpsMeasurement(d,start+4200);
 d=advanceDuelGpsMeasurement(d,syntheticPoint(51,start+5000),start+5000);
 d=advanceDuelGpsMeasurement(d,syntheticPoint(56,start+6000),start+6000);
 assert.equal(gpsGapDiagnostics(d.sprint).finishTimingMethod,'observed-after-gap');
 assert.equal(gpsGapDiagnostics(d.sprint).gpsObservationGapCount,0);
});
test('ghost and field local exports include diagnostic aggregates but private saved summaries do not',()=>{
 let s=apply(createGpsSprint(50,start),0,0);
 s=apply(s,10,4000);
 const local=ghostTraceDiagnostics(s,0,null);
 assert.equal(local.gpsObservationGapCount,1);
 assert.equal(local.gpsLongestObservationGapMs,4000);
 const saved=ghostSummary(s,0,0,0,'unavailable',false,false);
 for(const key of ['gpsObservationGapCount','gpsLongestObservationGapMs','finishTimingMethod'])assert.equal(key in saved,false);
 const field=readFileSync(new URL('../src/screens/GpsFieldTestScreen.tsx',import.meta.url),'utf8');
 assert.match(field,/\.\.\.\(measurement \? gpsGapDiagnostics\(measurement\) : \{\}\)/);
});
